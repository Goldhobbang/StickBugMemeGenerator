function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ko' || saved === 'en') return saved;
  } catch {
    /* Storage can be blocked. Fall through to the browser language. */
  }
  const locale = typeof navigator === 'undefined' ? '' : navigator.language.toLowerCase();
  return locale.startsWith('ko') ? 'ko' : 'en';
}

let lang: Lang = initialLang();
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return lang;
}

export function setLang(next: Lang): void {
  if (next !== 'ko' && next !== 'en') return;
  if (next === lang) return;
  lang = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* Ignore private-mode storage failures. */
  }
  listeners.forEach((listener) => listener());
}

export function onLangChange(listener: () => void): void {
  listeners.add(listener);
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split('{' + name + '}').join(String(value));
    }
  }
  return text;
}

export function applyI18n(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => {
    const key = el.dataset.i18nTitle;
    if (key) el.title = t(key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => {
    const key = el.dataset.i18nAria;
    if (key) el.setAttribute('aria-label', t(key));
  });
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang === 'ko' ? 'ko' : 'en';
    document.querySelectorAll<HTMLButtonElement>('#lang-ko, #lang-en').forEach((button) => {
      button.classList.toggle('active', button.id === 'lang-' + lang);
    });
  }
}

export function languageKeys(): { ko: string[]; en: string[] } {
  return { ko: Object.keys(STRINGS.ko), en: Object.keys(STRINGS.en) };
}
